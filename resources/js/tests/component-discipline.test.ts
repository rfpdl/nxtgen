import { readFileSync } from 'node:fs'
import { basename, join, relative } from 'node:path'
import { globSync } from 'glob'
import { describe, expect, it } from 'vitest'

/**
 * The atomic-design gate.
 *
 * Built from the canonical house rules rather than copied from palo, because palo's version was
 * inspected and differs from the standard in three ways: it has no story rule, it caps pages at 400,
 * and it does not check composables at all. This takes palo's eight rules — four of which the generic
 * skill does not mention and which are worth having — and applies the house page cap of 200 and
 * composable cap of 500.
 *
 * There is deliberately NO `.stories.ts` rule. Decided 2026-09-07 (plan §11.5): `.test.ts` siblings
 * instead, following palo and aegis. The written standard mandates stories and both live projects do
 * not; that discrepancy is the standard's to resolve, not this project's to absorb.
 *
 * There is also deliberately no regex banning fixed widths. It would flag `min-w-0` and `min-w-full`,
 * miss `w-96`, rem widths and inline styles, and fight the A4 print sheet. Overflow is asserted as an
 * OUTCOME in Playwright instead (plan §5.9) — a static rule that is routinely wrong gets allowlisted
 * and then ignored.
 */
// `process.cwd()` rather than `import.meta.url`: under Vitest the latter resolves through the dev
// server and comes back as a `/@fs/...` path, which then concatenates wrongly. Vitest runs from the
// project root.
const ROOT = process.cwd()
const JS = join(ROOT, 'resources/js')

/**
 * `components/ui/**` is VENDORED shadcn-vue and is exempt from every rule below.
 *
 * Not a loophole — an honest boundary. Those files are not ours: they are regenerated by
 * `npx shadcn-vue add`, so a test we wrote beside one would be deleted by the next update, a
 * REGISTRY entry would go stale, and their internal `any`s and utility classes are upstream's
 * business. Policing them would mean either editing vendor code (which the next regeneration
 * discards) or allowlisting rule by rule until the rules mean nothing.
 *
 * What keeps them safe instead is the CSS bridge in `app.css`: they are written against semantic
 * names, and those names point at our contrast-checked palette. So a vendored button inherits our
 * 7:1 pairs without this file having an opinion about it.
 *
 * OUR components — atoms, molecules, organisms, layout, pages — are still fully covered. If a rule
 * here ever needs to exempt one of those, that is a signal about the rule, not about the component.
 */
const VENDORED = '**/components/ui/**'

function files(pattern: string): string[] {
    return globSync(pattern, { cwd: ROOT, absolute: true, ignore: VENDORED }).sort()
}

function lineCount(file: string): number {
    return readFileSync(file, 'utf-8').trimEnd().split('\n').length
}

function rel(file: string): string {
    return relative(ROOT, file)
}

/** Source lines with comments and blank lines removed, for rules that must not match prose. */
function codeLines(file: string): { line: string; number: number }[] {
    return readFileSync(file, 'utf-8')
        .split('\n')
        .map((line, index) => ({ line, number: index + 1 }))
        .filter(({ line }) => {
            const trimmed = line.trim()

            return (
                trimmed !== '' &&
                !trimmed.startsWith('//') &&
                !trimmed.startsWith('*') &&
                !trimmed.startsWith('/*') &&
                !trimmed.startsWith('<!--')
            )
        })
}

describe('size limits', () => {
    const LIMITS: Record<string, number> = {
        atoms: 100,
        molecules: 200,
        organisms: 400,
    }

    for (const [layer, limit] of Object.entries(LIMITS)) {
        it(`${layer} are <= ${limit} lines`, () => {
            const over = files(`resources/js/components/${layer}/**/*.vue`)
                .map((file) => ({ file: rel(file), lines: lineCount(file) }))
                .filter(({ lines }) => lines > limit)

            expect(over, 'Extract a child component rather than compressing this one').toEqual([])
        })
    }

    it('pages are <= 200 lines', () => {
        // 200, not palo's 400. A page wires organisms together and owns data flow; when it needs
        // more than 200 lines it has stopped wiring and started implementing.
        const over = files('resources/js/pages/**/*.vue')
            .map((file) => ({ file: rel(file), lines: lineCount(file) }))
            .filter(({ lines }) => lines > 200)

        expect(over, 'Extract an organism — a page wires things together').toEqual([])
    })

    it('composables are <= 500 lines', () => {
        const over = files('resources/js/composables/**/*.ts')
            .filter((file) => !file.endsWith('.test.ts'))
            .map((file) => ({ file: rel(file), lines: lineCount(file) }))
            .filter(({ lines }) => lines > 500)

        expect(over, 'Split into focused composables').toEqual([])
    })
})


import { readFileSync } from 'node:fs'
import { basename, join, relative } from 'node:path'
import { globSync } from 'glob'
import { describe, expect, it } from 'vitest'

/**
 * The atomic-design gate.
 *
 * Built from the canonical house rules rather than copied from palo, because palo's version was
 * inspected and differs from the standard in three ways: it has no story rule, it caps pages at 400,
 * and it does not check composables at all. This takes palo's eight rules — four of which the generic
 * skill does not mention and which are worth having — and applies the house page cap of 200 and
 * composable cap of 500.
 *
 * There is deliberately NO `.stories.ts` rule. Decided 2026-09-07 (plan §11.5): `.test.ts` siblings
 * instead, following palo and aegis. The written standard mandates stories and both live projects do
 * not; that discrepancy is the standard's to resolve, not this project's to absorb.
 *
 * There is also deliberately no regex banning fixed widths. It would flag `min-w-0` and `min-w-full`,
 * miss `w-96`, rem widths and inline styles, and fight the A4 print sheet. Overflow is asserted as an
 * OUTCOME in Playwright instead (plan §5.9) — a static rule that is routinely wrong gets allowlisted
 * and then ignored.
 */
// `process.cwd()` rather than `import.meta.url`: under Vitest the latter resolves through the dev
// server and comes back as a `/@fs/...` path, which then concatenates wrongly. Vitest runs from the
// project root.
const ROOT = process.cwd()
const JS = join(ROOT, 'resources/js')

/**
 * `components/ui/**` is VENDORED shadcn-vue and is exempt from every rule below.
 *
 * Not a loophole — an honest boundary. Those files are not ours: they are regenerated by
 * `npx shadcn-vue add`, so a test we wrote beside one would be deleted by the next update, a
 * REGISTRY entry would go stale, and their internal `any`s and utility classes are upstream's
 * business. Policing them would mean either editing vendor code (which the next regeneration
 * discards) or allowlisting rule by rule until the rules mean nothing.
 *
 * What keeps them safe instead is the CSS bridge in `app.css`: they are written against semantic
 * names, and those names point at our contrast-checked palette. So a vendored button inherits our
 * 7:1 pairs without this file having an opinion about it.
 *
 * OUR components — atoms, molecules, organisms, layout, pages — are still fully covered. If a rule
 * here ever needs to exempt one of those, that is a signal about the rule, not about the component.
 */
const VENDORED = '**/components/ui/**'

function files(pattern: string): string[] {
    return globSync(pattern, { cwd: ROOT, absolute: true, ignore: VENDORED }).sort()
}

function lineCount(file: string): number {
    return readFileSync(file, 'utf-8').trimEnd().split('\n').length
}

function rel(file: string): string {
    return relative(ROOT, file)
}

/** Source lines with comments and blank lines removed, for rules that must not match prose. */
function codeLines(file: string): { line: string; number: number }[] {
    return readFileSync(file, 'utf-8')
        .split('\n')
        .map((line, index) => ({ line, number: index + 1 }))
        .filter(({ line }) => {
            const trimmed = line.trim()

            return (
                trimmed !== '' &&
                !trimmed.startsWith('//') &&
                !trimmed.startsWith('*') &&
                !trimmed.startsWith('/*') &&
                !trimmed.startsWith('<!--')
            )
        })
}

describe('size limits', () => {
    const LIMITS: Record<string, number> = {
        atoms: 100,
        molecules: 200,
        organisms: 400,
    }

    for (const [layer, limit] of Object.entries(LIMITS)) {
        it(`${layer} are <= ${limit} lines`, () => {
            const over = files(`resources/js/components/${layer}/**/*.vue`)
                .map((file) => ({ file: rel(file), lines: lineCount(file) }))
                .filter(({ lines }) => lines > limit)

            expect(over, 'Extract a child component rather than compressing this one').toEqual([])
        })
    }

    it('pages are <= 200 lines', () => {
        // 200, not palo's 400. A page wires organisms together and owns data flow; when it needs
        // more than 200 lines it has stopped wiring and started implementing.
        const over = files('resources/js/pages/**/*.vue')
            .map((file) => ({ file: rel(file), lines: lineCount(file) }))
            .filter(({ lines }) => lines > 200)

        expect(over, 'Extract an organism — a page wires things together').toEqual([])
    })

    it('composables are <= 500 lines', () => {
        const over = files('resources/js/composables/**/*.ts')
            .filter((file) => !file.endsWith('.test.ts'))
            .map((file) => ({ file: rel(file), lines: lineCount(file) }))
            .filter(({ lines }) => lines > 500)

        expect(over, 'Split into focused composables').toEqual([])
    })
})

describe('naming', () => {
    it('every composable is named useXxx.ts', () => {
        const bad = files('resources/js/composables/**/*.ts')
            .filter((file) => !file.endsWith('.test.ts'))
            .filter((file) => !/^use[A-Z]/.test(basename(file)))
            .map(rel)

        expect(bad).toEqual([])
    })
})

describe('layer dependency direction', () => {
    it('atoms import no other component layer', () => {
        const bad = files('resources/js/components/atoms/**/*.vue')
            .filter((file) => !file.endsWith('.test.ts'))
            .flatMap((file) =>
                codeLines(file)
                    .filter(({ line }) =>
                        /from '@\/components\/(molecules|organisms|layout)/.test(line),
                    )
                    .map(({ number }) => `${rel(file)}:${number}`),
            )

        expect(bad, 'An atom that needs a molecule is not an atom').toEqual([])
    })

    it('molecules do not import organisms or layout', () => {
        const bad = files('resources/js/components/molecules/**/*.vue').flatMap((file) =>
            codeLines(file)
                .filter(({ line }) => /from '@\/components\/(organisms|layout)/.test(line))
                .map(({ number }) => `${rel(file)}:${number}`),
        )

        expect(bad).toEqual([])
    })
})

describe('design tokens', () => {
    it('no component or page uses a raw Tailwind colour', () => {
        // Raw colours are decisions made in one component that cannot be revisited anywhere else,
        // and teacher screens have a hard 7:1 contrast requirement (plan §5.10) that can only be
        // held if the pairs live in one place. Semantic tokens only.
        const RAW =
            /\b(?:bg|text|border|ring|from|to|via|fill|stroke|divide|outline|shadow|accent|decoration)-(?:slate|gray|grey|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)-\d{2,3}\b/

        const bad = [
            ...files('resources/js/components/**/*.vue'),
            ...files('resources/js/pages/**/*.vue'),
        ].flatMap((file) =>
            codeLines(file)
                .filter(({ line }) => RAW.test(line))
                .map(({ number, line }) => `${rel(file)}:${number} → ${line.trim().slice(0, 80)}`),
        )

        expect(bad, 'Use a semantic token from app.css').toEqual([])
    })

    it('no door-facing component uses a subtle text colour', () => {
        // There is no `text-text-subtle` token, on purpose — it is the first thing to disappear in
        // a bright foyer. This catches anyone reintroducing one.
        const bad = [
            ...files('resources/js/components/**/*.vue'),
            ...files('resources/js/pages/Door/**/*.vue'),
        ].flatMap((file) =>
            codeLines(file)
                .filter(({ line }) => /text-(?:text-)?subtle|opacity-[1-5]0\b/.test(line))
                .map(({ number }) => `${rel(file)}:${number}`),
        )

        expect(bad, 'Use size, weight or space for de-emphasis — not less contrast').toEqual([])
    })
})

describe('typescript', () => {
    it('no component, page or composable uses explicit any', () => {
        const bad = [
            ...files('resources/js/components/**/*.vue'),
            ...files('resources/js/pages/**/*.vue'),
            ...files('resources/js/composables/**/*.ts'),
        ].flatMap((file) =>
            codeLines(file)
                .filter(({ line }) => /(?::\s*any\b|as\s+any\b|<any>)/.test(line))
                .map(({ number }) => `${rel(file)}:${number}`),
        )

        expect(bad).toEqual([])
    })
})

describe('badge reuse', () => {
    it('no inline badge colour map outside atoms', () => {
        // The pattern to watch for: `rounded-full` with a `bg-*-soft`/`text-*` pair written outside
        // atoms/ is a duplicate of BaseBadge — and the duplicate is the one that quietly fails 7:1.
        const bad = [
            ...files('resources/js/components/molecules/**/*.vue'),
            ...files('resources/js/components/organisms/**/*.vue'),
            ...files('resources/js/pages/**/*.vue'),
        ].flatMap((file) =>
            codeLines(file)
                .filter(({ line }) => /rounded-full/.test(line) && /bg-\w+-soft/.test(line))
                .map(({ number }) => `${rel(file)}:${number}`),
        )

        expect(bad, 'Use BaseBadge, or add a variant to it').toEqual([])
    })
})

describe('test siblings', () => {
    it('every component has a sibling .test.ts', () => {
        // This is the rule adopted INSTEAD of `.stories.ts` (plan §11.5), so it has to actually
        // exist — swapping one requirement for another and then enforcing neither would be worse
        // than either choice.
        const missing = files('resources/js/components/**/*.vue')
            .filter((file) => !globSync(file.replace(/\.vue$/, '.test.ts')).length)
            .map(rel)

        expect(missing, 'Add a sibling .test.ts — props in, rendering out').toEqual([])
    })

    it('every composable with logic has a sibling .test.ts', () => {
        const missing = files('resources/js/composables/**/*.ts')
            .filter((file) => !file.endsWith('.test.ts'))
            .filter((file) => !globSync(file.replace(/\.ts$/, '.test.ts')).length)
            .map(rel)

        expect(missing).toEqual([])
    })
})

describe('registry', () => {
    it('every component appears in REGISTRY.md', () => {
        const registry = readFileSync(join(JS, 'components/REGISTRY.md'), 'utf-8')

        const missing = files('resources/js/components/**/*.vue')
            .map((file) => basename(file, '.vue'))
            .filter((name) => !registry.includes(name))

        expect(missing, 'Add it to resources/js/components/REGISTRY.md').toEqual([])
    })
})

describe('the "Coming" list', () => {
    /*
     * A registry row for a component that already exists is worse than no row: a reader checking
     * whether something has been built is told no. `GuardianPicker`, `StarAwardRow`,
     * `AdminOverrideModal` and `PendingPrintTable` all sat under "Coming" for weeks after they
     * shipped.
     *
     * The gate above enforces the other direction — every component has a row. This is the pair to
     * it.
     */
    it('names only components that do not exist yet', () => {
        const registry = readFileSync(join(ROOT, 'resources/js/components/REGISTRY.md'), 'utf-8')

        /*
         * TABLE ROWS ONLY. Scanning the whole section caught the paragraph that explains which
         * components used to be listed here wrongly — the guard flagged its own documentation, which
         * is the most literal way to write a test that cannot pass.
         */
        const rows = registry
            .slice(registry.indexOf('## Coming'))
            .split('\n')
            .filter((line) => line.startsWith('|') && !line.startsWith('|---'))

        const named = rows.flatMap((row) =>
            [...row.matchAll(/`([A-Z][A-Za-z]+)`/g)].map((match) => match[1]),
        )

        const built = new Set(
            files('resources/js/components/**/*.vue').map((file) => basename(file, '.vue')),
        )

        const alreadyHere = named.filter((name) => name !== undefined && built.has(name))

        expect(
            alreadyHere,
            'These are listed as "Coming" in REGISTRY.md and already exist. Move them into the ' +
                'main table with what they actually do',
        ).toEqual([])
    })
})

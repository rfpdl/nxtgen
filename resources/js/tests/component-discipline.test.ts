describe('the "Coming" list', () => {
    /*
     * A registry row for a component that already exists is worse than no row: a reader checking
     * whether something has been built is told no. `GuardianPicker`, `StarAwardRow`,
     * `AdminOverrideModal` and `PendingPrintTable` all sat under "Coming" for weeks after they
     * shipped.
     *
     * The gate above enforces the other direction — every component has a row. This is the pair to
     * it.
     */
    it('names only components that do not exist yet', () => {
        const registry = readFileSync(join(ROOT, 'resources/js/components/REGISTRY.md'), 'utf-8')

        /*
         * TABLE ROWS ONLY. Scanning the whole section caught the paragraph that explains which
         * components used to be listed here wrongly — the guard flagged its own documentation, which
         * is the most literal way to write a test that cannot pass.
         */
        const rows = registry
            .slice(registry.indexOf('## Coming'))
            .split('\n')
            .filter((line) => line.startsWith('|') && !line.startsWith('|---'))

        const named = rows.flatMap((row) =>
            [...row.matchAll(/`([A-Z][A-Za-z]+)`/g)].map((match) => match[1]),
        )

        const built = new Set(
            files('resources/js/components/**/*.vue').map((file) => basename(file, '.vue')),
        )

        const alreadyHere = named.filter((name) => name !== undefined && built.has(name))

        expect(
            alreadyHere,
            'These are listed as "Coming" in REGISTRY.md and already exist. Move them into the ' +
                'main table with what they actually do',
        ).toEqual([])
    })
})
